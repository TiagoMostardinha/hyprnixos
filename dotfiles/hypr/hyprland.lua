-- Hyprland entry point (Lua config, Hyprland 0.55).
-- https://wiki.hypr.land/0.55.0/Configuring/Start/
--
-- Each require() runs in its own scope; share values by returning them
-- (see colors.lua). Environment variables live in ~/.config/uwsm/env
-- (modules/home/hyprland.nix), not here.

local colors = require("colors")

require("autostart")
require("binds")
require("rules")

-- Fallback for any screen. Real monitors come from host.lua (loaded last).
hl.monitor({
    output   = "",
    mode     = "preferred",
    position = "auto",
    scale    = "auto",
})

hl.config({
    general = {
        gaps_in     = 2,
        gaps_out    = 4,
        border_size = 2,
        col = {
            active_border   = colors.accent,
            inactive_border = colors.inactive,
        },
        resize_on_border = false,
        allow_tearing    = false,
        layout           = "dwindle",
    },

    decoration = {
        rounding = 0,
        shadow   = { enabled = false },
        blur     = { enabled = false },
    },

    animations = {
        enabled = false,
    },

    dwindle = {
        preserve_split = true,
    },

    misc = {
        force_default_wallpaper  = 0,
        disable_hyprland_logo    = true,
        disable_splash_rendering = true,
        -- Let a restarted Quickshell take over the lock if it crashed while locked.
        allow_session_lock_restore = true,
    },

    input = {
        kb_layout    = "pt",
        follow_mouse = 1,
        sensitivity  = 0,
        touchpad = {
            natural_scroll = false,
        },
    },
})

hl.gesture({
    fingers   = 3,
    direction = "horizontal",
    action    = "workspace",
})

-- Host-specific monitors and devices, generated by hosts/<name>/home.nix.
-- dofile, not require: require() only searches next to this (symlinked) file.
-- Kept last and unguarded so its errors show up in `hyprctl configerrors`.
local configHome = os.getenv("XDG_CONFIG_HOME") or (os.getenv("HOME") .. "/.config")
dofile(configHome .. "/hypr/host.lua")
